// this was a direct, explicit font choice (URL supplied), not a default
// picked on this session's own judgment.
//
// History before this: six hardware-confirmed rounds, documented in git
// history / this session's own log rather than repeated here in full --
// Picopixel (6px, upscaled 3x, looked like pixel art), FreeSans9pt7b (13px,
// legible but wanted smaller), FreeSans12pt7b (18px, "too big"), back to
// FreeSans9pt7b, then Ark Pixel Font's 10px (7px caps, too small), 16px
// (11px caps, too big), and 12px (9px cap height, closest fit yet from
// that family but still not settled), then GohuFont 14px (9px cap height,
// same as Ark Pixel 12px but monospace, purpose-drawn at this exact pixel
// size) -- confirmed "really good", GohuFont 11px (7px cap height) tried
// alongside it for comparison and both read fine, landed back on 14px.
//
// Chosen over building a font-rasterizer pipeline (`tools/lvgl_font_compiler`
// does that, but for LVGL's format, which this module cannot use -- no
// heap, no LVGL, no embassy in a panic handler) because BDF is already a
// bitmap format -- no rasterization step, just parsing already-drawn glyph
// bitmaps -- and reuses the same in-panic-handler rendering (`draw_glyph`
// below) every font tried in this module has used, monospace or not: a
// fixed `xAdvance` per glyph is just a proportional font whose advances all
// happen to be equal, nothing about `draw_glyph`/`draw_text_wrapped` needed
// to change.
//
// The bitmap and glyph tables below were extracted from `gohufont-14.bdf`
// and are checked in directly; this font has no build-time generator.
