/// Classical 45-degree clustered-dot screen, two interleaved dot centres per
/// 8x8 cell. The rotation is the whole point: the eye is least sensitive to
/// diagonal structure, which is why print screens black at 45 degrees. Growth
/// within a dot is by distance to its centre, tie-broken by angle so the dot
/// grows as a spiral disc -- an axis-aligned tie-break grows it into a bar
/// instead, which is what horizontal banding looks like.
const CLUSTERED8: [[u8; 8]; 8] = [
    [96, 40, 48, 104, 204, 176, 168, 192],
    [32, 0, 8, 56, 152, 236, 224, 128],
    [88, 24, 16, 64, 160, 240, 252, 184],
    [120, 80, 72, 112, 208, 136, 144, 220],
    [216, 180, 172, 212, 100, 44, 52, 108],
    [156, 248, 244, 132, 36, 4, 12, 60],
    [164, 228, 232, 188, 92, 28, 20, 68],
    [196, 140, 148, 200, 124, 84, 76, 116],
];

impl Screen {
    /// Threshold for this screen at a screen-space coordinate, 0..=255.
    fn threshold(self, x: i32, y: i32) -> u8 {
        match self {
            Self::Bayer => BAYER4[(y & 3) as usize][(x & 3) as usize],
            Self::BlueNoise => BLUE_NOISE32[(y & 31) as usize][(x & 31) as usize],
            Self::Clustered => CLUSTERED8[(y & 7) as usize][(x & 7) as usize],
        }
    }

    /// Whether the pixel at `(x, y)` is ink for a tone of `level` sixteenths.
    /// Clamped at both ends so a caller never has to special-case flat paper
    /// or flat ink.
    pub fn ink(self, x: i32, y: i32, level: u8) -> bool {
        if level == 0 {
            return false;
        }
        if level >= 16 {
            return true;
        }
        self.threshold(x, y) < level * 16
    }
}
