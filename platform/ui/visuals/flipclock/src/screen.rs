//! Halftone screens for the one-bit panel.
//!
//! All three are **threshold masks**: one table lookup and one compare per
//! pixel, indexed in *screen* space. That indexing is not a detail. A mask
//! indexed in screen space means an unchanged tone produces unchanged pixels,
//! so a region that is not moving costs nothing on a partial-refresh panel and
//! nothing flickers between frames. Error diffusion cannot offer that -- a
//! one-level tone change re-diffuses the whole region and every pixel flips --
//! which is why it is absent here despite being the better choice for a still
//! photograph.
//!
//! Tone is expressed in sixteenths throughout: 0 is paper, 16 is solid.

/// Which screen to render a tone through.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Default)]
pub enum Screen {
    /// Ordered 4x4. Cheapest, no table, and the most structured -- the grid is
    /// visible as crosshatch, and mid grey degenerates to a checkerboard.
    Bayer,
    /// Void-and-cluster blue noise, 32x32. Same cost as Bayer once the table
    /// is in flash, with no grid and no low-frequency clumping.
    #[default]
    BlueNoise,
    /// Classical clustered-dot AM screen, 8x8 at 45 degrees -- about 21 lines
    /// per inch at this panel's pitch. Coarser than the others, but it
    /// concentrates ink into larger features instead of isolated pixels: the
    /// thing to reach for if the panel turns out not to hold a single dark
    /// pixel at its nominal tone, which is a question only the glass can
    /// answer.
    Clustered,
}

